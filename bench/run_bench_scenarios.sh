#!/usr/bin/env bash
# Program-shaped scenarios: object churn, two-dimensional indexing, map lookup,
# method dispatch, string routines and a sort through a user comparator. The
# integer kernels measure the dispatch loop and the builtin benchmarks measure
# library code; these measure the mix ordinary programs are made of, and they
# include the workloads where Flaris's design is weakest. A second set, the
# standard benchmarks, comes from outside this project: programs that many
# language comparisons already use, so the choice of workload is not ours.
#
# The sources live in interp/, shared with run_interp.sh, which times the same
# programs interpreter-against-interpreter at the terminal. This runner adds
# the JIT lanes and publishes the tables.
#
# Normally invoked by run_bench.sh, which passes BENCH_REPORT/BENCH_APPEND so
# every half lands in one snapshot. Run it directly for a scenarios-only
# snapshot.
set -euo pipefail
cd "$(dirname "$0")"
BENCH_ROOT="$PWD"
source ./lib.sh

resolve_all_tools || exit 1
[[ -n "${BENCH_APPEND:-}" ]] || report_missing_tools

BENCH_TMP=$(mktemp -d "${TMPDIR:-/tmp}/flaris_bench_sc.XXXXXX")
trap 'rm -rf "$BENCH_TMP"' EXIT

mkdir -p "$BENCH_ROOT/results"
REPORT="${BENCH_REPORT:-$BENCH_ROOT/results/$(date +%Y-%m-%d)-$(machine_slug)-scenarios.md}"

cd "$BENCH_ROOT/interp"

SCENARIOS=(binarytrees matmul dict method strops sortcb)
STANDARD=(nbody spectralnorm fannkuch richards knucleotide)
ALL=("${SCENARIOS[@]}" "${STANDARD[@]}")
SC_LANGS=(py lua luajit luau luauc js node fls flsj)

# ── run ──────────────────────────────────────────────────────────────────────
run_lang() {  # run_lang <bench> <lang>
    local b="$1" l="$2"
    case "$l" in
      py)     run_one "$b" py     "$PYTHON" "bench_${b}.py" ;;
      lua)    run_one "$b" lua    "$LUA"    "bench_${b}.lua" ;;
      luajit) run_one "$b" luajit "$LUAJIT" "bench_${b}.lua" ;;
      luau)   run_one "$b" luau   "$LUAU" -O2 "bench_${b}.luau" ;;
      luauc)  run_one "$b" luauc  "$LUAU" -O2 --codegen "bench_${b}.luau" ;;
      js)     run_one "$b" js     "$QJS"    "bench_${b}.js" ;;
      node)   run_one "$b" node   "$NODE"   "bench_${b}.js" ;;
      # The JIT is on by default, so the plain-VM lane has to switch it OFF.
      fls)    run_one "$b" fls    "$FLARISVM" --strip --jit-disable "bench_${b}.fls" ;;
      flsj)   run_one "$b" flsj   "$FLARISVM" --strip "bench_${b}.fls" ;;
    esac
    return 0
}

for b in "${ALL[@]}"; do
    log "Running $b..."
    for l in "${SC_LANGS[@]}"; do run_lang "$b" "$l"; done
done

log "Checking result consistency..."
for b in "${ALL[@]}"; do check_bench "$b" "${SC_LANGS[@]}"; done

# ── report ───────────────────────────────────────────────────────────────────
base() { min_ms "$1" "${SC_LANGS[@]}"; }

{
if [[ -z "${BENCH_APPEND:-}" ]]; then
cat <<HEADER
# Flaris scenario benchmark results

**Date:** $(date +%Y-%m-%d)
**Machine:** $(cpu_name), $(os_name) ($(uname -m))
**Flaris VM:** $(flaris_version)

Generated by \`bench/run_bench_scenarios.sh\`. Every number is $(runs_phrase),
measured inside the program. Lower is better.

HEADER
fi

cat <<'INTRO'
## Scenarios

Six small programs shaped like the code people actually write: building and
discarding objects, walking a matrix, looking keys up in a map, calling
methods, splitting and joining strings, sorting through a comparator. They
were written to cover what ordinary programs spend their time on, not to suit
any one runtime, and two of them sit squarely on Flaris's weakest paths:
allocation churn (`binarytrees`) and chained indexing (`matmul`).

Every runtime here is a dynamic language, written idiomatically, with no
library beyond what ships with it. The JIT lanes - LuaJIT, Luau with native
code generation, Node/V8 and Flaris JIT - appear next to the interpreters, so
read each table for both tiers.

### 1. Binary trees - 14.6 M short-lived nodes

Build complete binary trees of depth 4 to 16 and walk each one to count its
nodes, many times over. Almost all of the time goes on creating a small object
and reclaiming it again, so this measures the allocator and the memory
manager rather than the bytecode. `result = 14,592,688` nodes.

INTRO

emit_table binarytrees "$(base binarytrees)" "vs fastest" 1 "${SC_LANGS[@]}"

cat <<'MATMUL'
### 2. Matrix multiply - 220 x 220 integers

The textbook triple loop over arrays of arrays, with the current row of `a`
hoisted out of the inner loop as any programmer would write it. Every step of
the inner loop reads `ai[k]` and `b[k][j]`, so it measures nested-loop
overhead and two-level indexing. `result = 51,108,200`.

MATMUL

emit_table matmul "$(base matmul)" "vs fastest" 1 "${SC_LANGS[@]}"

cat <<'DICT'
### 3. Map lookup - 200,000 string keys

Fill a string-keyed map with 200k entries, then look every key up three
times. Measures string hashing and the map implementation.
`result = 59,999,700,000`.

DICT

emit_table dict "$(base dict)" "vs fastest" 1 "${SC_LANGS[@]}"

cat <<'METHOD'
### 4. Method calls - 6 M calls on one instance

Call two small methods on an object in a loop. The work inside each method is
trivial, so this measures finding the method and paying for the call.
`result = 54,000,027,000,000`.

METHOD

emit_table method "$(base method)" "vs fastest" 1 "${SC_LANGS[@]}"

cat <<'STROPS'
### 5. String routines - split, search and join, 120,000 times

Split a CSV line, search the line for a word and join the pieces back
together. Nearly all of the work happens inside each language's own string
library.
`result = 6,480,000`.

STROPS

emit_table strops "$(base strops)" "vs fastest" 1 "${SC_LANGS[@]}"

cat <<'SORTCB'
### 6. Sort with a comparator - 120,000 integers, 6 sorts

Sort through a comparison function written in the language itself, so every
comparison is a call from the runtime's sort back into user code. Python has
no comparator argument; it uses `functools.cmp_to_key`, which is the idiomatic
way to sort by a two-argument comparison there. `result = 6,000,126`.

SORTCB

emit_table sortcb "$(base sortcb)" "vs fastest" 1 "${SC_LANGS[@]}"

cat <<'STANDARD'
## Standard benchmarks

The scenarios above were written for this suite. These five were not: four
come from The Computer Language Benchmarks Game and one is Martin Richards'
scheduler simulation, which V8, PyPy and pyperformance all use. They are here
so that at least part of the comparison runs on workloads nobody chose to suit
Flaris. Every language has its own straightforward implementation of the
published algorithm, written as an ordinary program in that language, and all
of them must agree on the result.

### 1. nbody - five bodies, 200,000 steps

The Jovian planets integrated with a fixed time step. Floating-point arithmetic
on the fields of five small objects; how cheaply a runtime handles a float in an
object field decides it. `result = 338,158,877` (the energy before and after,
in units of 1e-9).

STANDARD

emit_table nbody "$(base nbody)" "vs fastest" 1 "${SC_LANGS[@]}"

cat <<'SPECTRAL'
### 2. spectral-norm - size 800

The spectral norm of an infinite matrix by ten power iterations: float
multiply-adds in nested loops over float arrays, with a small integer formula
for each matrix element. `result = 1,274,224,144` (the norm, times 1e9).

SPECTRAL

emit_table spectralnorm "$(base spectralnorm)" "vs fastest" 1 "${SC_LANGS[@]}"

cat <<'FANNKUCH'
### 3. fannkuch-redux - 10 elements

Every permutation of ten elements, counting the pancake flips each needs.
Small integer-array reads, writes and swaps in short loops.
`result = 73,196,038` (checksum 73,196, at most 38 flips).

FANNKUCH

emit_table fannkuch "$(base fannkuch)" "vs fastest" 1 "${SC_LANGS[@]}"

cat <<'RICHARDS'
### 4. richards - 500 runs

An operating-system scheduler handing packets between idle, worker, handler
and device tasks. Method calls on small objects and following links between
them - the shape of most object-oriented code. `result = 5,002,322,928`.

RICHARDS

emit_table richards "$(base richards)" "vs fastest" 1 "${SC_LANGS[@]}"

cat <<'KNUC'
### 5. k-nucleotide - 2,000,000 bases

Every substring of length 1, 2, 3, 4, 6, 12 and 18 counted in a string-keyed
map. Substring creation, string hashing and map updates - work that sits in C
in most runtimes, CPython's dictionaries included. `result = 146,237,196`.

KNUC

emit_table knucleotide "$(base knucleotide)" "vs fastest" 1 "${SC_LANGS[@]}"

} >> "$REPORT"

echo ""
echo "═══════════════════════════════════════════════════════════════════════════════════"
echo "  SCENARIOS  (ms, lower is better)"
echo "═══════════════════════════════════════════════════════════════════════════════════"
printf "  %-13s" "Language"; for b in "${ALL[@]}"; do printf "%13s" "$b"; done; echo
for l in "${SC_LANGS[@]}"; do
    row=""; any=""
    for b in "${ALL[@]}"; do
        ms=$(get_ms "$b" "$l"); [[ "$ms" != "N/A" ]] && any=1
        row+=$(printf "%13s" "$ms")
    done
    [[ -n "$any" ]] && printf "  %-13s%s\n" "$(lang_name "$l")" "$row"
done
echo "═══════════════════════════════════════════════════════════════════════════════════"
echo ""
log "Scenario results written - $REPORT"
